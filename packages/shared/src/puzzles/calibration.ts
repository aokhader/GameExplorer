// ---------------------------------------------------------------------------
// Least squares — the Go structural fit
// ---------------------------------------------------------------------------

/**
 * Ridge-regularised least squares: solve `(XᵀX + λI)b = Xᵀy` for `b`.
 *
 * The ridge term is not decoration. The Go model is fitted to **fourteen**
 * hand-rated problems on four features, two of which — region size and the
 * log of the solver's node count — measure very nearly the same thing, because
 * a wider region is exactly what makes the search bigger. `XᵀX` is therefore
 * close to singular, and an unregularised solve answers with enormous
 * coefficients of opposite sign that fit those fourteen points beautifully and
 * predict nothing. λ trades a little fit for a model that generalises, which is
 * the entire purpose here.
 *
 * Add your own bias column; this fits exactly the columns it is given.
 */
export function fitLeastSquares(
  design: readonly (readonly number[])[],
  targets: readonly number[],
  lambda = 1,
): number[] {
  const n = design.length;
  if (n === 0 || targets.length !== n) {
    throw new Error('fitLeastSquares: design and targets must be the same non-zero length');
  }
  const p = design[0].length;

  // Normal equations, built directly — p is tiny (five here), so there is no
  // reason to reach for a decomposition.
  const a: number[][] = Array.from({ length: p }, () => Array<number>(p).fill(0));
  const b: number[] = Array<number>(p).fill(0);
  for (let i = 0; i < n; i++) {
    for (let j = 0; j < p; j++) {
      b[j] += design[i][j] * targets[i];
      for (let k = 0; k < p; k++) a[j][k] += design[i][j] * design[i][k];
    }
  }
  for (let j = 0; j < p; j++) a[j][j] += lambda;

  // Gauss-Jordan with partial pivoting.
  for (let col = 0; col < p; col++) {
    let pivot = col;
    for (let row = col + 1; row < p; row++) {
      if (Math.abs(a[row][col]) > Math.abs(a[pivot][col])) pivot = row;
    }
    if (Math.abs(a[pivot][col]) < 1e-12) continue; // column carries no information
    [a[col], a[pivot]] = [a[pivot], a[col]];
    [b[col], b[pivot]] = [b[pivot], b[col]];

    const d = a[col][col];
    for (let k = col; k < p; k++) a[col][k] /= d;
    b[col] /= d;

    for (let row = 0; row < p; row++) {
      if (row === col) continue;
      const factor = a[row][col];
      if (factor === 0) continue;
      for (let k = col; k < p; k++) a[row][k] -= factor * a[col][k];
      b[row] -= factor * b[col];
    }
  }
  return b;
}

/** The design row for one Go problem, in the order `GoStructuralModel` names. */
export function goDesignRow(f: GoStructuralFeatures): number[] {
  return [1, f.regionSize, f.logNodes, f.losingMoves];
}

export function goModelFrom(coefficients: readonly number[]): GoStructuralModel {
  const [intercept, regionSize, logNodes, losingMoves] = coefficients;
  return { intercept, regionSize, logNodes, losingMoves };
}
